-- Domain keys are a SEPARATE contract: digits, dots and hyphens are
-- semantically load-bearing in a hostname, so `7eleven.com` must never fold the
-- way a name does. Takes an ALREADY-EXTRACTED host — URL parsing and IDNA
-- happen upstream on the client, because PostgreSQL ships neither and a
-- mismatched IDNA implementation is exactly the drift this design prevents.
CREATE OR REPLACE FUNCTION merchant_domain_key_v1(input TEXT)
RETURNS TEXT
LANGUAGE sql
IMMUTABLE
PARALLEL SAFE
RETURNS NULL ON NULL INPUT
AS $$
  SELECT CASE
    WHEN host ~ '^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$'
      THEN host
    ELSE ''
  END
  FROM (
    SELECT regexp_replace(
             regexp_replace(
               translate(btrim(input, ' '), U&'\0041\0042\0043\0044\0045\0046\0047\0048\0049\004A\004B\004C\004D\004E\004F\0050\0051\0052\0053\0054\0055\0056\0057\0058\0059\005A', U&'\0061\0062\0063\0064\0065\0066\0067\0068\0069\006A\006B\006C\006D\006E\006F\0070\0071\0072\0073\0074\0075\0076\0077\0078\0079\007A'),
               '^www\.', ''
             ),
             '\.$', ''
           ) AS host
  ) s;
$$;

