-- ---------------------------------------------------------------------------
-- 2. merchant_lookup_noise_v1 — the write guard's predicate
--
-- The device's lookup pipeline removes acquirer boilerplate and
-- marker-introduced identifiers BEFORE looking a merchant up. That stripping is
-- deliberately outside the frozen key (a lexicon inside the key would make every
-- new bank prefix a full key-version migration). The cost of that choice is that
-- the catalog must never contain an alias the pipeline would strip — otherwise
-- the same string resolves differently depending on which stage matched it:
--
--   alias `cafe term 4471` -> merchant A,  alias `cafe` -> merchant B
--   query "CAFE TERM 4471" hits A unstripped, and B if stripped first.
--
-- The system cannot call a suffix noise and simultaneously allow it inside a
-- reviewed identity. So this predicate recognises EVERY construct the pipeline
-- can remove, and the trigger below rejects any alias containing one.
--
-- It runs on the CANONICALISED form, never on raw text: a whitespace-only regex
-- is evadable, because `POS-PURCHASE CARREFOUR` becomes `pos purchase carrefour`
-- on the device but never matches `\s`-based matching on the raw string.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION merchant_lookup_noise_v1(input TEXT)
RETURNS BOOLEAN
LANGUAGE sql
IMMUTABLE
PARALLEL SAFE
AS $$
  SELECT k ~ (
      -- anchored multi-word acquirer wrappers. Bare `pos`, `purchase`,
      -- `payment`, `شراء`, `دفع` are deliberately ABSENT: they are plausible
      -- beginnings of real business names, and stripping them turns
      -- "PAYMENT SOLUTIONS" into a different merchant called "Solutions".
      '^(pos purchase|card purchase|purchase at|payment to|point of sale'
      || '|شراء من|مشتريات من|عمليه شراء|دفع الى) '
    )
    OR k ~ (
      -- marker-introduced identifiers. The digits are REQUIRED (`+`, not `*`):
      -- text_normalizer.dart:36 uses `*`, which strips a bare trailing token and
      -- turns "CAFE TRACE" into "CAFE".
      '(^| )(branch|term|terminal|ref|txn|trace|auth|فرع|ترمينال|مرجع) [0-9]+( |$)'
    )
  FROM (SELECT merchant_alias_key_v1(input) AS k) s;
$$;

COMMENT ON FUNCTION merchant_lookup_noise_v1(TEXT) IS
  'True when a string contains something MerchantLookupPipeline.v1 would strip. Mirrors the client lexicon; see docs/coupons/MERCHANT_ALIAS_KEY_V1.md.';

