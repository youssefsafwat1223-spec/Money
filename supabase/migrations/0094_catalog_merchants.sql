CREATE TABLE IF NOT EXISTS catalog_merchants (
  id            UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  slug          TEXT NOT NULL UNIQUE,
  name_ar       TEXT NOT NULL,
  name_en       TEXT,
  primary_domain TEXT,
  logo_path     TEXT,
  default_display_category_key TEXT REFERENCES coupon_categories(key),
  -- {} means global. Same convention as coupons.country_codes.
  country_codes TEXT[] NOT NULL DEFAULT '{}',
  is_active     BOOLEAN NOT NULL DEFAULT TRUE,
  -- Tombstone, never hard-deleted: a delta client that never sees the row
  -- disappear would keep a merchant forever.
  is_deleted    BOOLEAN NOT NULL DEFAULT FALSE,
  created_version BIGINT NOT NULL DEFAULT 0,
  updated_version BIGINT NOT NULL DEFAULT 0,
  deleted_version BIGINT,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),

  CONSTRAINT catalog_merchants_slug_shape CHECK (slug ~ '^[a-z0-9][a-z0-9-]{1,62}$'),
  CONSTRAINT catalog_merchants_name_ar_present CHECK (btrim(name_ar) <> ''),
  -- Mirrors coupons_country_codes_shape (0081): array_to_string keeps it a
  -- simple immutable expression, since CHECK cannot contain a subquery.
  CONSTRAINT catalog_merchants_country_codes_shape CHECK (
    country_codes = '{}'::text[]
    OR array_to_string(country_codes, ',') ~ '^[A-Z]{2}(,[A-Z]{2})*$'
  ),
  -- Server-derived storage path only; never a client-shaped or traversing one.
  CONSTRAINT catalog_merchants_logo_path_shape CHECK (
    logo_path IS NULL OR logo_path ~ '^merchants/[0-9a-f-]{36}/[A-Za-z0-9_.-]+$'
  ),
  -- A domain here is a HOST, matching merchant_domain_key_v1's contract.
  CONSTRAINT catalog_merchants_primary_domain_shape CHECK (
    primary_domain IS NULL
    OR primary_domain = merchant_domain_key_v1(primary_domain)
  )
);

CREATE INDEX IF NOT EXISTS idx_catalog_merchants_live
  ON catalog_merchants (is_active) WHERE NOT is_deleted;

-- ---------------------------------------------------------------------------
-- 4. catalog_merchant_aliases
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS catalog_merchant_aliases (
  id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  merchant_id UUID NOT NULL REFERENCES catalog_merchants(id) ON DELETE CASCADE,

  -- The value a human entered. Kept because merchant_id is the identity and
  -- alias_normalized is only a lookup key: without the original there is nothing
  -- to review, debug, or re-key against when a v2 key function arrives.
  alias_raw   TEXT NOT NULL,

  alias_kind  TEXT NOT NULL,

  -- DERIVED, never supplied. PostgreSQL rejects an explicit value for a
  -- GENERATED ALWAYS column outright — there is no OVERRIDING escape hatch as
  -- there is for identity columns — so an admin request cannot smuggle a key
  -- that does not match its own raw value.
  alias_normalized TEXT GENERATED ALWAYS AS (
    CASE alias_kind
      WHEN 'name'   THEN merchant_alias_key_v1(alias_raw)
      WHEN 'domain' THEN merchant_domain_key_v1(alias_raw)
    END
  ) STORED,

  key_version INT NOT NULL DEFAULT 1,

  -- NULL means global.
  country_code TEXT,
  priority     INT NOT NULL DEFAULT 0,
  provenance   TEXT NOT NULL DEFAULT 'admin',
  -- Provider-suggested aliases arrive unreviewed and are NOT served to devices.
  is_reviewed  BOOLEAN NOT NULL DEFAULT FALSE,
  is_active    BOOLEAN NOT NULL DEFAULT TRUE,
  is_deleted   BOOLEAN NOT NULL DEFAULT FALSE,
  created_version BIGINT NOT NULL DEFAULT 0,
  updated_version BIGINT NOT NULL DEFAULT 0,
  deleted_version BIGINT,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at   TIMESTAMPTZ NOT NULL DEFAULT now(),

  -- NOT NULL + CHECK together: without both, the CASE above falls through to
  -- NULL and the alias silently has no key.
  CONSTRAINT catalog_merchant_aliases_kind CHECK (alias_kind IN ('name','domain')),
  CONSTRAINT catalog_merchant_aliases_provenance
    CHECK (provenance IN ('admin','provider','observed_candidate')),
  CONSTRAINT catalog_merchant_aliases_country_shape
    CHECK (country_code IS NULL OR country_code ~ '^[A-Z]{2}$'),
  -- Only v1 exists. An unconstrained, admin-writable version label would be a
  -- lie waiting to happen.
  CONSTRAINT catalog_merchant_aliases_key_version CHECK (key_version = 1),
  -- THE empty-key guard. Every input that folds away — all punctuation, all
  -- diacritics, a rejected Unicode host — produces ''. Without this they would
  -- all share one key and match each other.
  CONSTRAINT catalog_merchant_aliases_key_nonempty CHECK (alias_normalized <> ''),
  CONSTRAINT catalog_merchant_aliases_raw_present CHECK (btrim(alias_raw) <> '')
);

-- An active REVIEWED alias resolves to exactly one merchant. Scoped on
-- COALESCE(country_code,'') so a global row and a country row may legitimately
-- coexist — the device abstains between them unless it has merchant-location
-- evidence.
--
-- A partial unique INDEX, not a table constraint: PostgreSQL has no
-- `UNIQUE (...) WHERE ...` constraint syntax, and the expression rules it out
-- besides.
CREATE UNIQUE INDEX IF NOT EXISTS idx_merchant_aliases_unique_live
  ON catalog_merchant_aliases (alias_normalized, alias_kind, COALESCE(country_code, ''))
  WHERE is_active AND NOT is_deleted AND is_reviewed;

CREATE INDEX IF NOT EXISTS idx_merchant_aliases_merchant
  ON catalog_merchant_aliases (merchant_id) WHERE NOT is_deleted;
CREATE INDEX IF NOT EXISTS idx_merchant_aliases_review_queue
  ON catalog_merchant_aliases (is_reviewed, created_at) WHERE NOT is_deleted;

-- ---------------------------------------------------------------------------
-- 5. The write guard
--
-- Runs BEFORE, on NEW.alias_raw. It cannot read NEW.alias_normalized: generated
-- columns are computed AFTER before-triggers.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION trg_guard_merchant_alias() RETURNS TRIGGER AS $$
BEGIN
  IF NEW.alias_kind = 'name' AND merchant_lookup_noise_v1(NEW.alias_raw) THEN
    RAISE EXCEPTION
      'alias % contains acquirer boilerplate or a marker identifier that the device would strip before lookup; store the merchant name alone',
      NEW.alias_raw
      USING ERRCODE = 'check_violation';
  END IF;
  NEW.updated_at := now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_merchant_aliases_guard ON catalog_merchant_aliases;
CREATE TRIGGER trg_merchant_aliases_guard
  BEFORE INSERT OR UPDATE ON catalog_merchant_aliases
  FOR EACH ROW EXECUTE FUNCTION trg_guard_merchant_alias();

DROP TRIGGER IF EXISTS trg_catalog_merchants_updated_at ON catalog_merchants;
CREATE TRIGGER trg_catalog_merchants_updated_at
  BEFORE UPDATE ON catalog_merchants
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ---------------------------------------------------------------------------
-- 6. Delta versioning — the 0002 idiom, with 0093's lesson applied
--
-- 0006 shipped merchant_keywords with a catalog_versions row and no trigger to
-- bump it, so every device that synced once was pinned forever. These tables
-- get their bump at creation time, not later.
