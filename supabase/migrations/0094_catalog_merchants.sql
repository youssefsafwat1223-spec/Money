INSERT INTO catalog_versions (category, version, updated_at) VALUES
  ('catalog_merchants', 1, now()),
  ('merchant_aliases',  1, now())
ON CONFLICT (category) DO NOTHING;

CREATE OR REPLACE FUNCTION trg_version_catalog_merchants() RETURNS TRIGGER AS $$
DECLARE v BIGINT;
BEGIN
  v := nextval('catalog_seq_catalog_merchants');
  IF TG_OP = 'INSERT' THEN
    NEW.created_version := v; NEW.updated_version := v;
  ELSIF TG_OP = 'UPDATE' THEN
    NEW.updated_version := v;
    IF NEW.is_deleted AND NOT OLD.is_deleted THEN NEW.deleted_version := v; END IF;
  END IF;
  UPDATE catalog_versions SET version = v, updated_at = now()
   WHERE category = 'catalog_merchants';
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_catalog_merchants_version ON catalog_merchants;
CREATE TRIGGER trg_catalog_merchants_version
  BEFORE INSERT OR UPDATE ON catalog_merchants
