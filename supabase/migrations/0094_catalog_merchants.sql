-- ---------------------------------------------------------------------------
-- 8. Verification — fail the migration rather than report a half-applied one
-- ---------------------------------------------------------------------------
DO $$
DECLARE n INT; k TEXT;
BEGIN
  -- the generated column must actually be generated
  SELECT is_generated INTO k FROM information_schema.columns
   WHERE table_name = 'catalog_merchant_aliases' AND column_name = 'alias_normalized';
  IF k IS DISTINCT FROM 'ALWAYS' THEN
    RAISE EXCEPTION '0094: alias_normalized is not a generated column (%)', k;
  END IF;

  SELECT count(*) INTO n FROM pg_indexes
   WHERE tablename = 'catalog_merchant_aliases'
     AND indexname = 'idx_merchant_aliases_unique_live';
  IF n <> 1 THEN RAISE EXCEPTION '0094: the alias uniqueness index is missing'; END IF;

  SELECT count(*) INTO n FROM catalog_versions
   WHERE category IN ('catalog_merchants','merchant_aliases');
  IF n <> 2 THEN RAISE EXCEPTION '0094: catalog_versions rows missing (%)', n; END IF;

  -- the frozen keys must behave; a silent regeneration error would otherwise
  -- only surface as merchants that never resolve on device
  IF merchant_alias_key_v1('  CARREFOUR 24  ') <> 'carrefour 24' THEN
    RAISE EXCEPTION '0094: merchant_alias_key_v1 is not the frozen v1 contract';
  END IF;
  IF merchant_domain_key_v1('WWW.7Eleven.com.') <> '7eleven.com' THEN
    RAISE EXCEPTION '0094: merchant_domain_key_v1 is not the frozen v1 contract';
  END IF;
  IF NOT merchant_lookup_noise_v1('POS PURCHASE CARREFOUR')
     OR NOT merchant_lookup_noise_v1('CAFE TERM 4471')
     OR merchant_lookup_noise_v1('PAYMENT SOLUTIONS')
     OR merchant_lookup_noise_v1('CAFE TRACE') THEN
    RAISE EXCEPTION '0094: merchant_lookup_noise_v1 does not match the client lexicon';
  END IF;
END $$;
