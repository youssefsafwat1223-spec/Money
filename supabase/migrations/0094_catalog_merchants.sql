-- 0094 — canonical merchant catalog (COUPONS Phase 1).
--
-- Coupons today carry a free-text `partner_name`. That is enough to display an
-- offer and useless for deciding whether an offer is relevant to a user, because
-- "NOON", "noon.com" and "نون" are three strings and one company. This migration
-- adds the server-authored canonical merchant identity plus the reviewed aliases
-- that map real bank-message merchant strings onto it.
--
-- WHAT THIS DELIBERATELY IS NOT
--
-- It is not a personalization service. Merchant resolution and interest scoring
-- happen ENTIRELY ON DEVICE, from the local transaction ledger, and nothing
-- derived from a user's spending is ever sent here. The server publishes a
-- catalog; the device decides what it means. That is why there is no user column
-- anywhere in this file.
--
-- It is not fuzzy matching. An alias resolves exactly or the device abstains.
-- For categorization a false match costs a wrong chip; for "you shop here a lot"
-- derived from someone's bank messages, a false match is a trust breach in a
-- finance app. Recall is an alias-coverage problem solved by data — NOON,
-- NOONCOM, NOON KSA, noon.com as four reviewed aliases — not by an algorithm
-- that guesses.

